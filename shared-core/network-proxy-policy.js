// SPDX-License-Identifier: AGPL-3.0-only Network proxy policy. A forward proxy
// in the sandbox's network namespace, configured from the substrate allowlist
// and wired in via HTTP_PROXY / HTTPS_PROXY, so a fetch to a host the operator
// never allowed is refused at the network edge rather than trusted to the
// caller. Parity with substrate web_fetch. WebSocket / raw TCP: deny by
// default, explicit operator approval. What ships here (substrate side): -
// buildSquidConfig({allowed_hosts, audit_log_path}) — emits a squid conf
// string operator can drop into a sidecar - buildMitmproxyAddon() — emits a
// Python addon that reads the substrate allowlist + writes denial audits -
// mirrorAllowlistToProxyConfig(opts) — writes both configs to ~/.troth/proxy/
// for sidecar to pick up - recordSidecarDenial({host, reason, goal_id}) —
// substrate-side audit row (parity with l4_allowlist_audit) Actual sidecar
// process (running squid OR mitmproxy as a container network-namespace
// neighbor) is OPERATOR-side / sandbox-runtime . This module is the policy
// bridge. - STRUCTURAL allowlist — substrate refuses to write a permissive
// proxy config; the substrate allowlist IS the proxy allowlist (not two
// configs to drift) - out-of-process enforcement (proxy in different PID
// namespace than the LLM-driving substrate) - Common practice: mitmproxy
// addons for policy; squid acl http_access

'use strict';

const fs   = require('fs');
const path = require('path');
const state = require('./state.js');

const PROXY_DIR_DEFAULT = path.join(process.env.HOME || require('os').homedir(), '.troth', 'proxy');

function _ensureDir(dir) {
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
}

// Build a Squid 5.x config that ACL-allows only the listed hosts on
// HTTP CONNECT (HTTPS). Denies everything else with 403. Logs denials.
function buildSquidConfig(opts) {
  opts = opts || {};
  const allowed = Array.isArray(opts.allowed_hosts) ? opts.allowed_hosts : [];
  const auditLog = opts.audit_log_path || '/var/log/squid/troth-deny.log';
  const port = opts.port || 3128;
  const lines = [];
  lines.push('# Generated by troth network-proxy-policy — DO NOT EDIT BY HAND');
  lines.push('# Substrate allowlist mirror; regenerate via mirrorAllowlistToProxyConfig.');
  lines.push('http_port ' + port);
  lines.push('');
  lines.push('# Deny-by-default; allow only listed hosts.');
  if (allowed.length) {
    lines.push('acl troth_allow dstdomain ' + allowed.map(h => '.' + h).join(' '));
    lines.push('http_access allow troth_allow');
  } else {
    lines.push('# (no hosts allowed — substrate allowlist is empty)');
  }
  lines.push('http_access deny all');
  lines.push('');
  lines.push('# Log denials separately so substrate sidecar listener can ingest.');
  lines.push('logformat troth_deny %ts.%03tu %>a %ru %>Hs');
  lines.push('access_log ' + auditLog + ' troth_deny');
  lines.push('');
  lines.push('# Block raw TCP / WebSocket — operator must explicitly allow.');
  lines.push('acl SSL_ports port 443');
  lines.push('acl Safe_ports port 80 443');
  lines.push('http_access deny !Safe_ports');
  lines.push('http_access deny CONNECT !SSL_ports');
  return lines.join('\n');
}

// Build a mitmproxy Python addon that reads the allowlist from a sibling
// JSON file (substrate writes both atomically). Denies + logs anything
// not on the list.
function buildMitmproxyAddon(opts) {
  opts = opts || {};
  const auditPath = opts.audit_log_path || path.join(process.env.HOME || require('os').homedir(), '.troth', 'troth-mitm-deny.jsonl');
  const allowJsonPath = opts.allow_json_path || path.join(PROXY_DIR_DEFAULT, 'allowed_hosts.json');
  return [
    '# Generated by troth network-proxy-policy — mirrors substrate allowlist.',
    'import json, time',
    'from mitmproxy import http',
    '',
    'ALLOW_PATH = ' + JSON.stringify(allowJsonPath),
    'AUDIT_PATH = ' + JSON.stringify(auditPath),
    '',
    'def _load_allow():',
    '    try:',
    '        with open(ALLOW_PATH) as f:',
    '            return set(json.load(f).get("allowed_hosts", []))',
    '    except Exception:',
    '        return set()',
    '',
    '_ALLOW = _load_allow()',
    '_LAST = time.time()',
    '',
    'def request(flow: http.HTTPFlow):',
    '    global _ALLOW, _LAST',
    '    # Refresh allowlist every 30s without restart',
    '    if time.time() - _LAST > 30:',
    '        _ALLOW = _load_allow(); _LAST = time.time()',
    '    host = flow.request.pretty_host',
    '    if host not in _ALLOW and not any(host.endswith("." + d) for d in _ALLOW):',
    '        # Audit denial',
    '        try:',
    '            with open(AUDIT_PATH, "a") as f:',
    '                f.write(json.dumps({',
    '                    "ts": time.time(),',
    '                    "host": host,',
    '                    "url": flow.request.pretty_url,',
    '                    "method": flow.request.method,',
    '                    "reason": "not_in_substrate_allowlist"',
    '                }) + "\\n")',
    '        except Exception:',
    '            pass',
    '        flow.response = http.Response.make(',
    '            403, b"troth substrate proxy: host not in allowlist",',
    '            {"content-type": "text/plain"}',
    '        )'
  ].join('\n');
}

// Mirror substrate's web_fetch allowlist into proxy configs on disk.
// Operator's sidecar (squid or mitmproxy) reads these files.
//   opts.dir              — default ~/.troth/proxy
//   opts.allowed_hosts    — overrides substrate allowlist (testing)
function mirrorAllowlistToProxyConfig(opts) {
  opts = opts || {};
  const dir = opts.dir || PROXY_DIR_DEFAULT;
  _ensureDir(dir);

  let hosts = opts.allowed_hosts;
  if (!Array.isArray(hosts)) {
    try {
      const webAllow = require('./tools/web-allowlist.js');
      hosts = (typeof webAllow.listAllowed === 'function') ? webAllow.listAllowed() : [];
    } catch (_) { hosts = []; }
  }

  const squidPath = path.join(dir, 'squid.conf');
  const mitmPath  = path.join(dir, 'mitm_addon.py');
  const allowJson = path.join(dir, 'allowed_hosts.json');

  fs.writeFileSync(squidPath, buildSquidConfig({ allowed_hosts: hosts }));
  fs.writeFileSync(mitmPath,  buildMitmproxyAddon({ allow_json_path: allowJson }));
  fs.writeFileSync(allowJson, JSON.stringify({ allowed_hosts: hosts, written_at: Date.now() }, null, 2));

  return { ok: true, squid_path: squidPath, mitm_addon_path: mitmPath, allow_json_path: allowJson, hosts };
}

// Record a sidecar denial — parity with l4_allowlist_audit. v1 calls
// the existing recordAllowlistAudit path so dashboard surfaces show
// proxy denials alongside web_fetch denials (one timeline).
function recordSidecarDenial(ev) {
  try {
    if (typeof state.recordAllowlistAudit === 'function') {
      return state.recordAllowlistAudit({
        host:       ev.host,
        sample_url: ev.url || ev.host,
        mode:       'proxy_sidecar',
        goal_id:    ev.goal_id || null,
        goal_class: ev.goal_class || null,
        action:     'denied_by_sidecar'
      });
    }
    return null;
  } catch (_) { return null; }
}

module.exports = {
  buildSquidConfig,
  buildMitmproxyAddon,
  mirrorAllowlistToProxyConfig,
  recordSidecarDenial,
  PROXY_DIR_DEFAULT
};
