# Interactive compaction evidence — closes the only gap in 04-compaction-layer5.md.
#
# What 04-compaction-layer5.md proves: pre-compact.mjs handles a realistic
# PreCompact payload correctly (synthetic driver via run.mjs).
#
# What it explicitly does NOT prove: Claude Code's native compaction path
# actually reaches our hook in a real interactive session.
#
# This script closes that gap. It launches a real `claude` interactive
# session against a scratch dir, instructs the session to do enough work
# to populate the substrate, then issues `/compact`, then snapshots the
# substrate's state.db for a `type='compact'` row that proves the hook
# fired.
#
# Outputs:
#   benchmarks/results/interactive-compaction-<timestamp>.md
#
# Requires:
#   - claude (Claude Code CLI) on PATH
#   - jq, sqlite3
#
# Usage:
#   bash benchmarks/compaction/interactive-evidence.sh
#
# This is a manual-run script: interactive `claude` is hard to drive
# headlessly. Operator launches it, follows the on-screen prompts, then
# runs the verification step.

set -u  # don't set -e: we want graceful failure messages

REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
TS="$(date +%Y-%m-%dT%H-%M-%S)"
SCRATCH="/tmp/troth-interactive-compact-$TS"
RESULT_MD="$REPO_ROOT/benchmarks/results/interactive-compaction-$TS.md"
PLUGIN_DB="$HOME/.claude/plugins/data/troth-troth-local/state.db"

mkdir -p "$SCRATCH"
cd "$SCRATCH" || exit 1

echo "=== Interactive compaction evidence harness ==="
echo "Scratch dir: $SCRATCH"
echo "Plugin DB:   $PLUGIN_DB"
echo

if ! command -v claude >/dev/null 2>&1; then
  echo "ERROR: claude CLI not on PATH. Install Claude Code and retry."
  exit 2
fi
if ! command -v jq >/dev/null 2>&1 || ! command -v sqlite3 >/dev/null 2>&1; then
  echo "ERROR: need jq + sqlite3 on PATH."
  exit 2
fi

# Snapshot baseline compact-row count BEFORE the session.
BEFORE=0
if [[ -f "$PLUGIN_DB" ]]; then
  BEFORE="$(sqlite3 "$PLUGIN_DB" "SELECT COUNT(*) FROM action_records WHERE type='compact';" 2>/dev/null || echo 0)"
fi
echo "Baseline type=compact rows in state.db: $BEFORE"
echo

# Seed enough scratch files so the session can read them and fill context.
for i in 1 2 3 4 5 6 7 8; do
  awk -v n=$i 'BEGIN{
    print "// scratch file " n " — seed content for compaction evidence";
    print "// Generated by interactive-evidence.sh on " strftime("%c");
    for(i=0;i<200;i++) printf "// line %d: lorem ipsum dolor sit amet, consectetur adipiscing elit. seed=%d\n", i, n;
  }' > "scratch-$i.js"
done

cat <<'EOF'
=== INSTRUCTIONS ===

1. A `claude` session is about to launch in this scratch dir. The plugin
   should auto-load (verify with /plugin list inside the session if unsure).

2. Inside the session, paste these prompts in order:

     Read all 8 scratch files in this directory and summarize what they
     contain in one paragraph.

   Then a follow-up:

     For each file, write a one-line description and save them as
     descriptions.md in this directory.

3. After the agent finishes those two prompts, run:

     /compact

   Wait for compaction to complete.

4. Type /exit (or Ctrl-D) to leave the session.

5. Re-run THIS script with the verification flag to check the result:

     bash benchmarks/compaction/interactive-evidence.sh --verify

EOF

if [[ "${1:-}" == "--verify" ]]; then
  echo
  echo "=== VERIFICATION ==="
  AFTER=0
  if [[ -f "$PLUGIN_DB" ]]; then
    AFTER="$(sqlite3 "$PLUGIN_DB" "SELECT COUNT(*) FROM action_records WHERE type='compact';" 2>/dev/null || echo 0)"
  fi
  DELTA=$((AFTER - BEFORE))
  echo "Compact rows: before=$BEFORE  after=$AFTER  delta=$DELTA"

  RESULT="UNCLEAR"
  if [[ "$DELTA" -ge 1 ]]; then
    RESULT="PASS — pre-compact hook fired in interactive session"
  else
    RESULT="FAIL — no new type=compact rows; hook did not fire"
  fi

  LATEST_COMPACT="$(sqlite3 "$PLUGIN_DB" \
    "SELECT id, datetime(timestamp/1000, 'unixepoch') FROM action_records WHERE type='compact' ORDER BY timestamp DESC LIMIT 1;" 2>/dev/null || true)"

  cat > "$RESULT_MD" <<MD
# Interactive Compaction Evidence — $TS

Result: **$RESULT**

| Metric | Value |
|---|---|
| Baseline compact rows | $BEFORE |
| Post-session compact rows | $AFTER |
| Delta | $DELTA |
| Latest compact row | $LATEST_COMPACT |
| Scratch dir | $SCRATCH |
| Plugin DB | $PLUGIN_DB |

## What this proves (or doesn't)

The synthetic driver \`benchmarks/compaction/run.mjs\` already proved
that \`pre-compact.mjs\` correctly handles a realistic PreCompact payload
(see \`04-compaction-layer5.md\`).

This harness closes the remaining gap by launching a real interactive
\`claude\` session and running \`/compact\` — the only path that proves
Claude Code's native compaction trigger actually reaches our hook.

## Reproduce

\`\`\`bash
bash benchmarks/compaction/interactive-evidence.sh         # runs session
bash benchmarks/compaction/interactive-evidence.sh --verify # verifies
\`\`\`
MD
  echo
  echo "Wrote: $RESULT_MD"
  echo "Result: $RESULT"
  exit 0
fi

echo "Launching: cd $SCRATCH && claude"
echo
exec claude
